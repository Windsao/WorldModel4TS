"""Generate the main results table in the convention used by the LSF literature.

Datasets are column groups with MSE/MAE subcolumns; best per column is bold, second best is
underlined; the last row counts first places. Writes paper/figures/main_table.tex.

usage: python paper/make_main_table.py
Numbers: PAPER_MATERIAL.md section 5 (baselines quoted from VisionTS++ Table 4 and VisionTS).
"""
