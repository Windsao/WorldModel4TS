def cells(row):
    """-> flat list of 14 values (or None): 6 datasets x (mse, mae) + avg mse, avg mae."""
    out = []
    for v in row[2]:
        out += [None, None] if v is None else [v[0], v[1]]
    out += [None, None] if row[3] is None else [row[3][0], row[3][1]]
    return out


def main(out="paper/figures/main_table.tex"):
    table = [cells(r) for r in ROWS]
    ncol = len(table[0])
    best, second = [], []
    for c in range(ncol):
        vals = sorted(v for v in (row[c] for row in table) if v is not None)
        best.append(vals[0] if vals else None)
        second.append(next((v for v in vals if v > vals[0]), None) if vals else None)

    def fmt(v, c):
        if v is None:
            return "--"
        s = f"{v:.3f}"
        if v == best[c]:
            return "\\textbf{" + s + "}"
        if second[c] is not None and v == second[c]:
            return "\\underline{" + s + "}"
        return s

    firsts = [sum(1 for c in range(12) if row[c] is not None and row[c] == best[c]) for row in table]

    L = []
    L.append("% generated by paper/make_main_table.py -- do not edit by hand")
    L.append("\\begin{table}[t]")
    L.append("\\caption{Zero-shot long-sequence forecasting. Each entry averages the four horizons "
             "$H\\in\\{96,192,336,720\\}$; MSE and MAE are computed on standardised values. Our model "
             "uses one checkpoint and one inference rule for all 24 cells. Baselines are quoted from "
             "\\citet{visiontspp} and \\citet{visionts}; `--' means the source does not report that "
             "dataset. \\textbf{Bold}: best. \\underline{Underlined}: second best. The last column counts "
             "first places over the twelve dataset columns.}")
    L.append("\\label{tab:main}")
    L.append("\\begin{center}")
    L.append("\\setlength{\\tabcolsep}{3pt}")
    L.append("\\scriptsize")
    L.append("\\begin{tabular}{l" + "cc" * 7 + "c}")
    L.append("\\toprule")
    L.append("\\multirow{2}{*}{Model} & " + " & ".join(
        f"\\multicolumn{{2}}{{c}}{{{d}}}" for d in DS + ["\\textbf{Avg}"]) +
        " & \\multirow{2}{*}{1\\textsuperscript{st}} \\\\")
    L.append(" ".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(7)))
    L.append(" & " + " & ".join(["MSE", "MAE"] * 7) + " & \\\\")
    L.append("\\midrule")
    prev = ROWS[0][1]
    for row, vals, nf in zip(ROWS, table, firsts):
        if row[1] != prev:
            L.append("\\midrule")
            prev = row[1]
        L.append(row[0] + " & " + " & ".join(fmt(v, c) for c, v in enumerate(vals)) +
                 f" & {nf if nf else '--'} \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    L.append("\\end{center}")
    L.append("\\end{table}")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write("\n".join(L) + "\n")
    print("wrote", out)
    print("first places:", {r[0]: n for r, n in zip(ROWS, firsts) if n})


if __name__ == "__main__":
    main()
